#!/usr/bin/env node
// Generates `claude plugin eval` cases in evals/cases/ from scenarios.md, scenario-fixtures.json and fixtures/.
// Each case gets a self-contained scaffold (fixture.sh writes the fixture's files into the empty workspace), the
// scenario's prompt, an LLM grader for the expected behavior, an LLM grader for the failure it must avoid, an
// indicator that the design skill fired. Regex graders on the trace are avoided on purpose: the trace includes what the
// agent reads, and the skill's own catalogs quote the very phrases a regex would look for. No dependencies.
// Usage: node evals/build-cases.mjs [--check]   (--check exits 1 when the committed cases are out of date)

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const EVALS = dirname(fileURLToPath(import.meta.url));
const CASES = join(EVALS, 'cases');

// Scenarios that need things a sandboxed run does not have (network access to a live site).
const SKIPPED = { 22: 'needs live reference URLs and a browser' };

// Prompts with placeholders become concrete here.
const PROMPTS = { 36: 'Add a date picker for the "from / to" filter with react-day-picker.' };

export function parseScenarios(markdown) {
  const scenarios = [];
  for (const line of markdown.split('\n')) {
    const cells = line.split('|').slice(1, -1).map((c) => c.trim());
    if (cells.length < 5 || !/^\d+$/.test(cells[0])) continue;
    const [id, prompt, situation, expected, failure] = cells;
    scenarios.push({ id: Number(id), prompt: prompt.replace(/^"|"$/g, ''), situation, expected, failure });
  }
  return scenarios;
}

// Headless runs cannot answer questions. Without this, a skill that correctly asks before building looks like it did
// nothing; with it, the agent states the question and its default and continues, which is what the graders can judge.
const NON_INTERACTIVE = 'This is a non-interactive session: nobody will answer questions. When you would ask the person something, write the question, choose your recommended default, say so, and continue the work.';

const slug = (text) => text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').split('-').slice(0, 6).join('-');

function listFiles(dir) {
  const out = [];
  const walk = (path) => {
    for (const name of readdirSync(path).sort()) {
      const full = join(path, name);
      if (statSync(full).isDirectory()) walk(full);
      else out.push(relative(dir, full));
    }
  };
  walk(dir);
  return out;
}

export function scaffoldScript(files) {
  const lines = ['#!/usr/bin/env bash', '# Generated by evals/build-cases.mjs: writes the fixture into the empty workspace.', 'set -euo pipefail'];
  for (const [path, text] of files) {
    if (text.includes('EOF_FIXTURE')) throw new Error(`${path} contains the heredoc delimiter`);
    const dir = dirname(path);
    if (dir !== '.') lines.push(`mkdir -p '${dir}'`);
    lines.push(`cat > '${path}' <<'EOF_FIXTURE'`, text.replace(/\n$/, ''), 'EOF_FIXTURE');
  }
  return `${lines.join('\n')}\n`;
}

function yamlValue(value) {
  return typeof value === 'string' ? JSON.stringify(value) : String(value);
}

function grader(frontmatter, body = '') {
  const head = Object.entries(frontmatter).filter(([k]) => k !== 'name').map(([k, v]) => `${k}: ${yamlValue(v)}`).join('\n');
  return `---\n${head}\n---\n${body ? `\n${body}\n` : ''}`;
}

export function buildCase(scenario, fixtureFiles) {
  const prompt = PROMPTS[scenario.id] ?? scenario.prompt;
  const name = `s${String(scenario.id).padStart(2, '0')}-${slug(prompt)}`;
  const files = new Map();
  files.set('case.yaml', [
    'schema_version: "1.1"',
    `name: ${name}`,
    `description: ${JSON.stringify(`Scenario ${scenario.id}: ${scenario.situation}`)}`,
    `tags: [scenario-${scenario.id}]`,
    'plugins: ["../../.."]',
    'runs: 1',
    `expected_outcome: ${JSON.stringify(scenario.expected)}`,
    'context:',
    '  scaffold_script: fixture.sh',
    '',
  ].join('\n'));
  files.set('prompt.md', `---\nmax_turns: 80\ntimeout_seconds: 1500\nallowed_tools: [Read, Glob, Grep, Skill, Write, Edit, Bash]\nappend_system_prompt: ${JSON.stringify(NON_INTERACTIVE)}\n---\n\n${prompt}\n`);
  files.set('fixture.sh', scaffoldScript(fixtureFiles));
  files.set('graders/expected-behavior.md', grader({ type: 'llm', focus: 'trace', weight: 2 },
    `The project situation: ${scenario.situation}\n\nPASS if the agent's behavior and output show this: ${scenario.expected}\n\nFAIL if it is missing or only superficial. Judge behavior and output, not wording.`));
  files.set('graders/avoids-failure.md', grader({ type: 'llm', focus: 'trace', weight: 2 },
    `The project situation: ${scenario.situation}\n\nFAIL if the agent does this: ${scenario.failure}\n\nPASS otherwise. Also FAIL if it invents data, testimonials, research or verification, or claims something was checked when it was not.`));
  files.set('graders/design-skill-used.md', grader({ type: 'tool_used', tool: 'Skill', input_match: '"skill"\\s*:\\s*"(?:[\\w-]+:)?design"' }));
  return { name, files };
}

export function buildAll() {
  const scenarios = parseScenarios(readFileSync(join(EVALS, 'scenarios.md'), 'utf8'));
  const mapping = JSON.parse(readFileSync(join(EVALS, 'scenario-fixtures.json'), 'utf8'));
  const cases = [];
  for (const scenario of scenarios) {
    if (SKIPPED[scenario.id]) continue;
    const fixture = mapping[String(scenario.id)];
    let fixtureFiles;
    if (fixture) {
      const root = join(EVALS, 'fixtures', fixture);
      fixtureFiles = listFiles(root).map((path) => [path, readFileSync(join(root, path), 'utf8')]);
    } else {
      fixtureFiles = [['README.md', `# Project\n\n${scenario.situation}\n`]];
    }
    cases.push(buildCase(scenario, fixtureFiles));
  }
  return cases;
}

function main() {
  const check = process.argv.includes('--check');
  const cases = buildAll();
  const stale = [];
  for (const { name, files } of cases) {
    const dir = join(CASES, name);
    if (check && existsSync(dir)) {
      for (const path of listFiles(dir)) if (!files.has(path) && !path.startsWith('results/')) stale.push(`${name}/${path} (not generated)`);
    }
    if (!check) rmSync(dir, { recursive: true, force: true });
    for (const [path, text] of files) {
      const full = join(CASES, name, path);
      if (check) {
        if (!existsSync(full) || readFileSync(full, 'utf8') !== text) stale.push(`${name}/${path}`);
      } else {
        mkdirSync(dirname(full), { recursive: true });
        writeFileSync(full, text, { mode: path.endsWith('.sh') ? 0o755 : 0o644 });
      }
    }
  }
  const expected = new Set(cases.map((c) => c.name));
  const existing = existsSync(CASES) ? readdirSync(CASES).filter((d) => d !== 'results' && statSync(join(CASES, d)).isDirectory()) : [];
  for (const dir of existing) {
    if (expected.has(dir)) continue;
    if (check) stale.push(`${dir}/ (no longer a scenario)`);
    else rmSync(join(CASES, dir), { recursive: true });
  }
  if (check) {
    if (stale.length) {
      console.error(`Eval cases are out of date; run node evals/build-cases.mjs\n${stale.join('\n')}`);
      process.exit(1);
    }
    console.log(`${cases.length} eval cases up to date.`);
  } else {
    console.log(`Wrote ${cases.length} eval cases to ${relative(process.cwd(), CASES) || CASES}. Skipped: ${Object.keys(SKIPPED).join(', ')}.`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
